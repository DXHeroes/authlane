/**
 * Compiles `integrations/<id>/icon.svg` into a TypeScript module the API can import.
 *
 * The API is built with a bare `tsc`, so nothing but TypeScript reaches `dist/`, and `serveStatic`
 * resolves against a working directory that differs between `pnpm dev`, the Docker image, and
 * vitest. A compiled-in map has none of those axes and needs no Dockerfile change.
 *
 * Every icon is rejected rather than sanitized. An SVG served from the API's own origin can execute
 * script, so anything that could carry behaviour fails the build where an author sees it, instead
 * of being quietly stripped into something nobody reviewed.
 */
import { createHash } from 'node:crypto';
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const integrationsDirectory = join(repositoryRoot, 'integrations');
const generatedPath = join(repositoryRoot, 'apps/api/src/generated/service-icons.ts');
const checkOnly = process.argv.includes('--check');

const MAX_ICON_BYTES = 16 * 1024;

const FORBIDDEN = [
  [/<script[\s>]/i, 'contains a <script> element'],
  [/<foreignObject[\s>]/i, 'contains a <foreignObject> element'],
  [/\son[a-z]+\s*=/i, 'contains an inline event handler attribute'],
  [/javascript:/i, 'contains a javascript: URL'],
  [/<!ENTITY/i, 'declares an XML entity'],
  [/(?:xlink:)?href\s*=\s*["']\s*(?:https?:)?\/\//i, 'references an external document'],
];

function reject(serviceId, reason) {
  throw new Error(`integrations/${serviceId}/icon.svg ${reason}. Icons must be inert markup.`);
}

function assertInert(serviceId, svg) {
  if (Buffer.byteLength(svg) > MAX_ICON_BYTES) {
    reject(serviceId, `is larger than ${MAX_ICON_BYTES} bytes`);
  }
  for (const [pattern, reason] of FORBIDDEN) {
    if (pattern.test(svg)) reject(serviceId, reason);
  }
  if (!/<svg[^>]*\sviewBox\s*=/i.test(svg)) {
    reject(serviceId, 'declares no viewBox, so it cannot scale to the box a card gives it');
  }
}

async function readIcons() {
  const entries = await readdir(integrationsDirectory, { withFileTypes: true });
  const icons = [];
  for (const entry of entries.sort((left, right) => (left.name < right.name ? -1 : 1))) {
    if (!entry.isDirectory()) continue;
    let svg;
    try {
      svg = await readFile(join(integrationsDirectory, entry.name, 'icon.svg'), 'utf8');
    } catch {
      // A service without an icon is a deliberate state: some marks are not ours to redistribute.
      // It renders from its brand colour and initials instead.
      continue;
    }
    assertInert(entry.name, svg);
    icons.push({
      serviceId: entry.name,
      svg: svg.trim(),
      etag: `"${createHash('sha256').update(svg).digest('hex').slice(0, 32)}"`,
    });
  }
  return icons;
}

const icons = await readIcons();

const output = `/**
 * Generated by scripts/generate-service-icons.mjs from integrations/<id>/icon.svg. Do not edit.
 *
 * Run \`pnpm icons:generate\` after changing an icon.
 */

export const SERVICE_ICON_SVG: Readonly<Record<string, string>> = Object.freeze({
${icons.map((icon) => `  '${icon.serviceId}': ${JSON.stringify(icon.svg)},`).join('\n')}
});

/** Strong validator per icon, so a card that already has one revalidates instead of refetching. */
export const SERVICE_ICON_ETAG: Readonly<Record<string, string>> = Object.freeze({
${icons.map((icon) => `  '${icon.serviceId}': ${JSON.stringify(icon.etag)},`).join('\n')}
});
`;

if (checkOnly) {
  let actual;
  try {
    actual = await readFile(generatedPath, 'utf8');
  } catch {
    throw new Error(`Generated artifact is missing: ${generatedPath}. Run pnpm icons:generate.`);
  }
  if (actual !== output) {
    throw new Error(`Generated artifact is stale: ${generatedPath}. Run pnpm icons:generate.`);
  }
} else {
  await mkdir(dirname(generatedPath), { recursive: true });
  await writeFile(generatedPath, output);
}
